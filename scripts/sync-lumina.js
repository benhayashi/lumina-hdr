#!/usr/bin/env node

/**
 * LuminaSync Bridge
 * Synchronizes layout, glassmorphic styling, and keyboard mapping from LuminaSaver
 * into LuminaHDR. Checks local LuminaSaver repo first, falling back to GitHub raw files.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const PROJECT_ROOT = path.resolve(__dirname, '..');

const LOCAL_CANDIDATES = [
  process.env.LUMINA_SAVER_DIR,
  path.resolve(PROJECT_ROOT, '../LuminaSaver'),
  path.resolve(PROJECT_ROOT, '../../LuminaSaver'),
  path.resolve(PROJECT_ROOT, 'external/lumina-saver')
].filter(Boolean);

const GITHUB_RAW_BASE = 'https://raw.githubusercontent.com/benhayashi/lumina-saver/main';

async function fetchSourceFile(relPath) {
  for (const dir of LOCAL_CANDIDATES) {
    const fullPath = path.join(dir, relPath);
    if (fs.existsSync(fullPath)) {
      console.log(`[LuminaSync] Reading local: ${fullPath}`);
      return fs.readFileSync(fullPath, 'utf8');
    }
  }

  const url = `${GITHUB_RAW_BASE}/${relPath}`;
  console.log(`[LuminaSync] Fetching remote: ${url}`);
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Failed to fetch ${url}: ${res.statusText}`);
  }
  return await res.text();
}

function parseGlassCardStyles(overlayCode) {
  // Extract QFrame styling from GlassCard
  const qframeMatch = overlayCode.match(/QFrame\s*\{([^}]+)\}/s);
  const qlabelMatch = overlayCode.match(/QLabel\s*\{([^}]+)\}/s);

  const styles = {
    bg: 'rgba(18, 22, 30, 0.72)',
    border: '1px solid rgba(255, 255, 255, 0.15)',
    borderRadius: '12px',
    padding: '10px 16px',
    textColor: '#FFFFFF',
    fontFamily: "'Segoe UI', 'Roboto', 'Inter', -apple-system, BlinkMacSystemFont, sans-serif",
    accentBlue: '#60A5FA',
    accentWarning: '#FBBF24',
    progressBarChunk: '#3B82F6',
    progressBarBg: 'rgba(255, 255, 255, 0.1)',
  };

  if (qframeMatch) {
    const block = qframeMatch[1];
    const bg = block.match(/background-color:\s*([^;]+);/i);
    if (bg) styles.bg = bg[1].trim();
    const border = block.match(/border:\s*([^;]+);/i);
    if (border) styles.border = border[1].trim();
    const br = block.match(/border-radius:\s*([^;]+);/i);
    if (br) styles.borderRadius = br[1].trim();
    const pad = block.match(/padding:\s*([^;]+);/i);
    if (pad) styles.padding = pad[1].trim();
  }

  if (qlabelMatch) {
    const block = qlabelMatch[1];
    const col = block.match(/color:\s*([^;]+);/i);
    if (col) styles.textColor = col[1].trim();
    const ff = block.match(/font-family:\s*([^;]+);/i);
    if (ff) styles.fontFamily = ff[1].trim();
  }

  // Check for specific accent color patterns in code
  const skyBlue = overlayCode.match(/color:\s*(#[0-9A-Fa-f]{6});.*sky blue/i);
  if (skyBlue) styles.accentBlue = skyBlue[1];

  const warningYellow = overlayCode.match(/color:\s*(#[0-9A-Fa-f]{6});/i);
  if (warningYellow) styles.accentWarning = warningYellow[1];

  return styles;
}

