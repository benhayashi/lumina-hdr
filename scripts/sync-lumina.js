async function main() {
  console.log('[LuminaSync] Starting LuminaSaver layout synchronization...');
  try {
    const overlayCode = await fetchSourceFile('lumina_saver/ui_overlay.py');
    const styles = parseGlassCardStyles(overlayCode);

    const cssPath = path.join(PROJECT_ROOT, 'src/client/css/lumina-theme.css');
    const jsPath = path.join(PROJECT_ROOT, 'src/client/js/lumina-layout-config.js');

    fs.mkdirSync(path.dirname(cssPath), { recursive: true });
    fs.mkdirSync(path.dirname(jsPath), { recursive: true });

    fs.writeFileSync(cssPath, generateThemeCSS(styles));
    console.log(`[LuminaSync] Updated ${cssPath}`);

    fs.writeFileSync(jsPath, generateLayoutConfig(styles));
    console.log(`[LuminaSync] Updated ${jsPath}`);

    console.log('[LuminaSync] ✅ Successfully synchronized layout from LuminaSaver!');
  } catch (err) {
    console.error(`[LuminaSync] ❌ Error syncing layout:`, err.message);
    process.exit(1);
  }
}

main();
